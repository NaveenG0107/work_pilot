"""LLM Provider abstraction and OpenAI-compatible integration for WorkPilot."""

from __future__ import annotations

import abc
import json
from dataclasses import dataclass, field
from typing import Any
import httpx

from src.config import (
    AI_API_KEY,
    AI_BASE_URL,
    AI_MODEL,
    AI_PROVIDER,
    AI_REQUEST_TIMEOUT_SECONDS,
    AI_TEMPERATURE,
    AI_MAX_OUTPUT_TOKENS,
    get_logger,
)

logger = get_logger(__name__)


class ProviderError(Exception):
    """Base exception for LLM provider errors."""

    def __init__(self, status_code: int, code: str, message: str) -> None:
        super().__init__(message)
        self.status_code = status_code
        self.code = code
        self.message = message


class ProviderTimeoutError(ProviderError):
    def __init__(self, message: str = "AI service request timed out.") -> None:
        super().__init__(504, "GATEWAY_TIMEOUT", message)


class ProviderRateLimitError(ProviderError):
    def __init__(self, message: str = "AI service rate limit exceeded. Please try again later.") -> None:
        super().__init__(429, "RATE_LIMIT_EXCEEDED", message)


class ProviderUnavailableError(ProviderError):
    def __init__(self, message: str = "AI service is currently unavailable.") -> None:
        super().__init__(503, "SERVICE_UNAVAILABLE", message)


class ProviderResponseError(ProviderError):
    def __init__(self, message: str = "Received invalid response from AI provider.") -> None:
        super().__init__(502, "BAD_GATEWAY", message)


@dataclass
class ToolCall:
    """Normalized tool call request generated by the model."""

    id: str
    name: str
    arguments: dict[str, Any]


@dataclass
class ProviderResponse:
    """Normalized completion response from the provider."""

    content: str | None
    tool_calls: list[ToolCall] = field(default_factory=list)
    finish_reason: str | None = None
    raw: dict[str, Any] = field(default_factory=dict)


class LLMProvider(abc.ABC):
    """Abstract interface for LLM providers."""

    @abc.abstractmethod
    async def generate_completion(
        self,
        messages: list[dict[str, str]],
        *,
        tools: list[dict[str, Any]] | None = None,
        tool_choice: str | dict[str, Any] = "auto",
        temperature: float | None = None,
        max_tokens: int | None = None,
    ) -> ProviderResponse:
        """Generate response from provider with optional function/tool calling."""
        pass


class OpenAICompatibleProvider(LLMProvider):
    """HTTP client for OpenAI or any OpenAI-compatible LLM endpoint."""

    def __init__(
        self,
        api_key: str | None = None,
        base_url: str | None = None,
        model: str | None = None,
        timeout_seconds: float | None = None,
    ) -> None:
        self.api_key = (api_key if api_key is not None else AI_API_KEY).strip()
        self.base_url = (base_url if base_url is not None else AI_BASE_URL).rstrip("/")
        self.model = model if model is not None else AI_MODEL
        self.timeout_seconds = timeout_seconds if timeout_seconds is not None else AI_REQUEST_TIMEOUT_SECONDS

    async def generate_completion(
        self,
        messages: list[dict[str, str]],
        *,
        tools: list[dict[str, Any]] | None = None,
        tool_choice: str | dict[str, Any] = "auto",
        temperature: float | None = None,
        max_tokens: int | None = None,
    ) -> ProviderResponse:
        if not self.api_key:
            logger.error("AI service configuration error: AI_API_KEY is not configured in environment.")
            raise ProviderUnavailableError("The AI assistant service is temporarily unavailable. Please contact your system administrator.")
        if not self.base_url:
            logger.error("AI service configuration error: AI_BASE_URL is not configured in environment.")
            raise ProviderUnavailableError("The AI assistant service is temporarily unavailable. Please contact your system administrator.")
        if not self.model:
            logger.error("AI service configuration error: AI_MODEL is not configured in environment.")
            raise ProviderUnavailableError("The AI assistant service is temporarily unavailable. Please contact your system administrator.")


        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }


        payload: dict[str, Any] = {
            "model": self.model,
            "messages": messages,
            "temperature": temperature if temperature is not None else AI_TEMPERATURE,
            "max_tokens": max_tokens if max_tokens is not None else AI_MAX_OUTPUT_TOKENS,
        }

        if tools:
            payload["tools"] = tools
            payload["tool_choice"] = tool_choice

        endpoint = f"{self.base_url}/chat/completions"

        try:
            async with httpx.AsyncClient(timeout=self.timeout_seconds) as client:
                response = await client.post(endpoint, headers=headers, json=payload)
        except httpx.TimeoutException as exc:
            logger.error("LLM Provider timed out after %s seconds: %s", self.timeout_seconds, exc)
            raise ProviderTimeoutError() from exc
        except (httpx.ConnectError, httpx.NetworkError) as exc:
            logger.error("Network error connecting to LLM provider at %s: %s", endpoint, exc)
            raise ProviderUnavailableError("Could not connect to AI provider.") from exc
        except Exception as exc:
            logger.error("Unexpected error contacting LLM provider: %s", exc, exc_info=True)
            raise ProviderUnavailableError("Failed to communicate with AI provider.") from exc

        if response.status_code == 429:
            logger.warning("LLM Provider returned 429 Rate Limit")
            raise ProviderRateLimitError()
        elif response.status_code in {502, 503, 504}:
            logger.warning("LLM Provider returned %s: %s", response.status_code, response.text)
            raise ProviderUnavailableError(f"AI provider returned status {response.status_code}")
        elif response.is_error:
            logger.error("LLM Provider error %s: %s", response.status_code, response.text)
            raise ProviderResponseError(f"AI provider returned error {response.status_code}")

        try:
            data = response.json()
        except Exception as exc:
            logger.error("Failed to parse JSON response from LLM provider: %s", exc)
            raise ProviderResponseError("Invalid JSON from AI provider.") from exc

        choices = data.get("choices")
        if not choices or not isinstance(choices, list):
            logger.error("Malformed completion response from provider: %s", data)
            raise ProviderResponseError("Malformed choices array in AI response.")

        first_choice = choices[0]
        message_data = first_choice.get("message", {})
        content = message_data.get("content")
        raw_tool_calls = message_data.get("tool_calls") or []

        tool_calls: list[ToolCall] = []
        for raw_call in raw_tool_calls:
            call_id = raw_call.get("id", "")
            fn_data = raw_call.get("function", {})
            fn_name = fn_data.get("name", "")
            args_str = fn_data.get("arguments", "{}")

            try:
                args = json.loads(args_str) if isinstance(args_str, str) else args_str
                if not isinstance(args, dict):
                    args = {}
            except Exception:
                logger.warning("Failed to decode JSON arguments for tool %s: %s", fn_name, args_str)
                args = {}

            tool_calls.append(ToolCall(id=call_id, name=fn_name, arguments=args))

        return ProviderResponse(
            content=content,
            tool_calls=tool_calls,
            finish_reason=first_choice.get("finish_reason"),
            raw=data,
        )


class MockLLMProvider(LLMProvider):
    """Configurable mock provider for tests and local development."""

    def __init__(self, canned_response: ProviderResponse | None = None) -> None:
        self.canned_response = canned_response
        self.history: list[dict[str, Any]] = []

    def set_response(self, response: ProviderResponse) -> None:
        self.canned_response = response

    async def generate_completion(
        self,
        messages: list[dict[str, str]],
        *,
        tools: list[dict[str, Any]] | None = None,
        tool_choice: str | dict[str, Any] = "auto",
        temperature: float | None = None,
        max_tokens: int | None = None,
    ) -> ProviderResponse:
        self.history.append({
            "messages": messages,
            "tools": tools,
            "tool_choice": tool_choice,
        })
        if self.canned_response:
            return self.canned_response

        # Default intelligent fallback for testing without external API key:
        # Detect if user message mentions creating a task
        last_user_msg = ""
        for m in reversed(messages):
            if m.get("role") == "user":
                last_user_msg = m.get("content", "").lower()
                break

        if "create" in last_user_msg and "task" in last_user_msg:
            # Extract basic context project_id if present in system/context
            return ProviderResponse(
                content=None,
                tool_calls=[
                    ToolCall(
                        id="mock_call_1",
                        name="create_task",
                        arguments={
                            "title": "Fix the login API",
                            "type": "bug" if "bug" in last_user_msg else "task",
                            "priority": "high" if "high" in last_user_msg else "medium",
                        },
                    )
                ],
                finish_reason="tool_calls",
            )

        return ProviderResponse(
            content="Hello! I am the WorkPilot AI Assistant. How can I help with your tasks today?",
            tool_calls=[],
            finish_reason="stop",
        )


_DEFAULT_PROVIDER: LLMProvider | None = None


def get_llm_provider() -> LLMProvider:
    """Return the configured LLM provider instance."""
    global _DEFAULT_PROVIDER
    if _DEFAULT_PROVIDER is None:
        if AI_PROVIDER == "mock":
            _DEFAULT_PROVIDER = MockLLMProvider()
        else:
            _DEFAULT_PROVIDER = OpenAICompatibleProvider()
    return _DEFAULT_PROVIDER


def set_llm_provider(provider: LLMProvider | None) -> None:
    """Set or reset the LLM provider instance (useful in tests)."""
    global _DEFAULT_PROVIDER
    _DEFAULT_PROVIDER = provider
